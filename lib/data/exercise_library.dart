/// Exercise knowledge library. Written as general fitness guidance, not
/// medical advice. Stop if something hurts, and ask a coach or doctor if unsure.
class ExerciseInfo {
  final String name;
  final String group;
  final String primary;
  final String secondary;
  final String equipment;
  final String level;
  final List<String> steps;
  final List<String> mistakes;
  final String beginner;
  final String intermediate;
  final String advanced;

  const ExerciseInfo({
    required this.name,
    required this.group,
    required this.primary,
    required this.secondary,
    required this.equipment,
    required this.level,
    required this.steps,
    required this.mistakes,
    required this.beginner,
    required this.intermediate,
    required this.advanced,
  });
}

const exerciseGroups = ['Chest', 'Back', 'Shoulders', 'Arms', 'Legs', 'Core', 'Cardio', 'Yoga', 'Stretch'];

/// Finds the library entry for a plan exercise name, ignoring case.
ExerciseInfo? findExercise(String name) {
  final n = name.trim().toLowerCase();
  for (final e in exerciseLibrary) {
    if (e.name.toLowerCase() == n) return e;
  }
  return null;
}

/// The muscle groups shown in the muscle volume analyzer.
const trackedMuscles = ['Chest', 'Back', 'Shoulders', 'Biceps', 'Triceps', 'Legs', 'Core'];

/// Which tracked muscle an exercise trains. Null for cardio and unknown
/// custom exercises.
String? muscleOf(String name) {
  final n = name.trim().toLowerCase();
  if (n.contains('curl') && !n.contains('leg')) return 'Biceps';
  if (n.contains('triceps') || n == 'dips' || n.contains('skull') || n.contains('kickback')) {
    return 'Triceps';
  }
  final info = findExercise(name);
  if (info == null) return null;
  switch (info.group) {
    case 'Chest':
    case 'Back':
    case 'Shoulders':
    case 'Legs':
    case 'Core':
      return info.group;
    case 'Arms':
      return 'Biceps';
    default:
      return null;
  }
}

/// Other exercises that train the same muscle, for when a machine is busy.
/// Closest first (same primary muscle), then the rest of the same muscle,
/// and entries with different equipment come before the same equipment.
/// True when an exercise can be done with the equipment the user has
/// (gym | home | none). Judged from the equipment text.
bool equipmentFits(String equipment, String? have) {
  if (have == null || have == 'gym') return true;
  final e = equipment.toLowerCase();
  if (have == 'none') return e.contains('bodyweight');
  // home: dumbbells, bands, bodyweight; no machines, cables or barbells.
  const gymOnly = ['machine', 'cable', 'barbell', 'smith', 'rack', 'lat pull', 'pulldown'];
  return !gymOnly.any(e.contains);
}

List<ExerciseInfo> alternativesFor(String name, {String? equipmentHave}) {
  final info = findExercise(name);
  if (info == null) return const [];
  final muscle = muscleOf(name);
  final out = <ExerciseInfo>[];
  for (final e in exerciseLibrary) {
    if (e.name == info.name) continue;
    final same = muscle != null ? muscleOf(e.name) == muscle : e.group == info.group;
    if (same) out.add(e);
  }
  int score(ExerciseInfo e) =>
      (equipmentFits(e.equipment, equipmentHave) ? 0 : 10) +
      (e.primary == info.primary ? 0 : 2) +
      (e.equipment == info.equipment ? 1 : 0);
  out.sort((a, b) => score(a).compareTo(score(b)));
  return out;
}

